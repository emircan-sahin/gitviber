"""Copies the Material Icon Theme SVGs GitViber's lookup can reach into assets/file-icons and
writes src/widgets/file_icon_map.rs. Run from the repo root with the npm package installed:
python3 crates/ui/tools/file_icons.py node_modules/material-icon-theme"""
import json, os, shutil, sys

pkg = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
out_dir = os.path.join(here, "..", "assets", "file-icons")
theme = json.load(open(os.path.join(pkg, "dist", "material-icons.json")))
version = json.load(open(os.path.join(pkg, "package.json")))["version"]
defs = theme["iconDefinitions"]
tables = {k: theme[k] for k in ["fileNames", "fileExtensions", "folderNames", "folderNamesExpanded", "languageIds"]}
used = {theme["file"], theme["folder"], theme["folderExpanded"]}
for t in tables.values():
    used.update(t.values())
used = sorted(i for i in used if i in defs)
# Sorted by asset path, which the lookup binary-searches ("go-mod.svg" sorts before "go.svg").
names = sorted({os.path.basename(defs[i]["iconPath"])[:-4] for i in used}, key=lambda n: "file-icons/%s.svg" % n)
index = {n: i for i, n in enumerate(names)}
icon_of = lambda i: index[os.path.basename(defs[i]["iconPath"])[:-4]]

shutil.rmtree(out_dir, ignore_errors=True)
os.makedirs(out_dir)
# GPUI rasterizes an <img> SVG once at its own size: 32px stays sharp at 16pt on a 2x display.
for n in names:
    svg = open(os.path.join(pkg, "icons", n + ".svg")).read()
    if " width=" not in svg.split(">", 1)[0]:
        svg = svg.replace("<svg ", '<svg width="32" height="32" ', 1)
    open(os.path.join(out_dir, n + ".svg"), "w").write(svg)
shutil.copy(os.path.join(pkg, "LICENSE"), os.path.join(out_dir, "LICENSE"))

def table(name, src):
    rows = sorted((k, icon_of(v)) for k, v in src.items() if v in defs)
    body = "".join("    (%s, %d),\n" % (json.dumps(k, ensure_ascii=False), v) for k, v in rows)
    return "pub(super) static %s: &[(&str, u16)] = &[\n%s];\n" % (name, body)

rs = ["// Generated by tools/file_icons.py from material-icon-theme %s (MIT). Do not edit.\n" % version]
rs.append("pub(super) static ICONS: &[(&str, &[u8])] = &[\n")
rs += ['    ("file-icons/%s.svg", include_bytes!("../../assets/file-icons/%s.svg")),\n' % (n, n) for n in names]
rs.append("];\n")
rs.append("pub(super) const FILE: u16 = %d;\npub(super) const FOLDER: u16 = %d;\npub(super) const FOLDER_OPEN: u16 = %d;\n"
          % (icon_of(theme["file"]), icon_of(theme["folder"]), icon_of(theme["folderExpanded"])))
for rust, key in [("FILE_NAMES", "fileNames"), ("FILE_EXTENSIONS", "fileExtensions"), ("FOLDER_NAMES", "folderNames"),
                  ("FOLDER_NAMES_OPEN", "folderNamesExpanded"), ("LANGUAGE_IDS", "languageIds")]:
    rs.append(table(rust, tables[key]))
open(os.path.join(here, "..", "src", "widgets", "file_icon_map.rs"), "w").write("".join(rs))
print(len(names), "icons")
